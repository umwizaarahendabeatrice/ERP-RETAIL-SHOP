// Usage (from repo root):  node tests/run-tests.js
// Loads the business logic from retail-erp.html and runs it without a browser.
const fs = require('fs'), path = require('path');
const html = fs.readFileSync(path.join(__dirname, '..', 'retail-erp.html'), 'utf8');
let js = html.match(/<script>([\s\S]*)<\/script>/)[1].replace('D=load();if(!D)init();render();', '');
global.localStorage = { _d: {}, getItem(k) { return this._d[k] || null }, setItem(k, v) { this._d[k] = v } };
global.document = { getElementById: () => ({ innerHTML: '', value: '' }) };
eval(js + `
let pass=0,fail=0;
const ok=(n,c)=>{c?pass++:fail++;console.log((c?'PASS ':'FAIL ')+n)};
const throws=(n,f)=>{try{f();ok(n,false)}catch(e){ok(n+' -> '+e.message,true)}};
const balanced=()=>D.jl.reduce((s,l)=>s+l.dr-l.cr,0)===0;
init();
ok('start: cash 3,393,000',bal('1000')===3393000);
ok('start: stock value 1,607,000',stockValue()===1607000);
ok('start: ledger balanced',balanced());
tx(()=>createSale(null,[{pid:1,qty:5}],'Cash'));
ok('sale: rice stock 35',D.products[0].qty===35);
ok('sale: revenue 140,000',-bal('4000')===140000);
ok('sale: gross profit 30,000',-bal('4000')-bal('5000')===30000);
ok('sale: cash 3,533,000',bal('1000')===3533000);
ok('sale: 4 new journal lines',D.jl.length===8+4);
throws('oversell rejected',()=>tx(()=>createSale(null,[{pid:2,qty:999}],'Cash')));
ok('oversell: stock unchanged',D.products[1].qty===25);
tx(()=>voidSale(1));
ok('void: stock restored',D.products[0].qty===40);
ok('void: cash and stock value restored',bal('1000')===3393000&&stockValue()===1607000);
throws('double void rejected',()=>tx(()=>voidSale(1)));
tx(()=>receive(1,40,26000));
ok('receive: avg cost 24,000',D.products[0].cost===24000);
ok('receive: stock 80',D.products[0].qty===80);
ok('receive: cash down 1,040,000',bal('1000')===3393000-1040000);
ok('receive: ledger matches stock value',Math.abs(bal('1200')-stockValue())<=3);
tx(()=>createSale(null,[{pid:2,qty:15}],'Cash'));
ok('reorder: oil at or below reorder level',D.products[1].qty<=D.products[1].reorder);
throws('duplicate SKU rejected',()=>tx(()=>addProduct({sku:'rice-5kg',name:'x',price:1,reorder:1})));
throws('negative price rejected',()=>tx(()=>addProduct({sku:'N1',name:'x',price:-5,reorder:1})));
throws('blank name rejected',()=>tx(()=>addProduct({sku:'N2',name:' ',price:5,reorder:1})));
throws('duplicate phone rejected',()=>tx(()=>addCustomer({name:'Z',phone:'0772 000 111'})));
tx(()=>createSale(1,[{pid:3,qty:1}],'Cash'));
throws('delete customer with sale rejected',()=>tx(()=>delCustomer(1)));
const t=tx(()=>addProduct({sku:'TEST',name:'Test',price:100,reorder:1}));
tx(()=>delProduct(t.id));
ok('add then delete a new product',!D.products.find(p=>p.sku==='TEST'));
throws('delete product with sales rejected',()=>tx(()=>delProduct(1)));
tx(()=>updProduct(3,{sku:'SUGAR-1KG',name:'Sugar',price:6000,reorder:20}));
tx(()=>createSale(null,[{pid:3,qty:1}],'Cash'));
ok('edited price used on new sale',D.items[D.items.length-1].price===6000);
throws('zero quantity rejected',()=>tx(()=>receive(1,0,100)));
throws('decimal quantity rejected',()=>tx(()=>receive(1,2.5,100)));
const before=JSON.stringify(D);
throws('multi-line sale fails as a whole',()=>tx(()=>createSale(null,[{pid:3,qty:1},{pid:2,qty:999}],'Cash')));
ok('rollback leaves data identical',JSON.stringify(D)===before);
ok('final: ledger balanced',balanced());
console.log('\\n'+pass+' passed, '+fail+' failed');
process.exitCode=fail?1:0;
`);
